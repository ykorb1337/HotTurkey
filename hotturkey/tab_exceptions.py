"""Ephemeral exceptions for one browser instance, tab and rule.

Grants never change policy, locks, breaks or application enforcement. Browser
instance IDs are generated by the extension worker, never by content scripts.
"""
import copy
import hashlib
import json
import re
from urllib.parse import urlsplit

from .engine import password_ok
from .model import PolicyError, integer


def scope(data):
    context=data.get('context')
    tab=data.get('tab')
    if not isinstance(context,str) or not re.fullmatch(r'[A-Za-z0-9_-]{32,128}',context):
        raise PolicyError('浏览器会话无效')
    if type(tab) is not int or not 0<=tab<=2147483647:raise PolicyError('标签页无效')
    return context,tab


class TabExceptions:
    def __init__(self, engine):
        self.engine=engine
        self.grants={}

    def revision(self, block):
        value=copy.deepcopy(block)
        for key in ['retry_at','ready_at']:value['lock'].pop(key,None)
        interval=self.engine.interval(block)
        value['_interval']=interval[:2] if interval else None
        value['_started']=self.engine.runtime(block).get('started')
        return hashlib.sha256(json.dumps(value,sort_keys=True,ensure_ascii=False,allow_nan=False).encode()).hexdigest()

    def _valid(self):
        now=self.engine.monotonic()
        blocks={b['id']:b for b in self.engine.store.state['blocks']}
        revisions={}
        for key,grant in list(self.grants.items()):
            ident=key[2]
            block=blocks.get(ident)
            if grant['until']<=now or block is None:
                del self.grants[key];continue
            if ident not in revisions:revisions[ident]=self.revision(block)
            if revisions[ident]!=grant['revision']:del self.grants[key]
        return self.grants

    def ids(self, data):
        if 'context' not in data and 'tab' not in data:return set()
        context,tab=scope(data)
        with self.engine.store.lock:
            return {key[2] for key in self._valid() if key[:2]==(context,tab)}

    def snapshot(self, context, tabs):
        scope({'context':context,'tab':0})
        if not isinstance(tabs,list) or len(tabs)>1000 or any(type(t) is not int or not 0<=t<=2147483647 for t in tabs):
            raise PolicyError('标签页列表无效')
        tabs=set(tabs)
        with self.engine.store.lock:
            now=self.engine.monotonic()
            return [{'id':key[2],'tab':key[1],'remaining':grant['until']-now,'revision':grant['revision']}
                    for key,grant in self._valid().items() if key[0]==context and key[1] in tabs]

    def close(self, data):
        context,tab=scope(data)
        with self.engine.store.lock:
            for key in list(self.grants):
                if key[:2]==(context,tab):del self.grants[key]
        return {'ok':True}

    def request(self, data):
        context,tab=scope(data)
        minutes=integer(data.get('minutes',5),1,1440,'临时放行分钟')
        url=data.get('url')
        if not isinstance(url,str) or len(url)>8192:raise PolicyError('网页地址无效')
        try:
            parsed=urlsplit(url)
            if parsed.scheme not in {'http','https'} or not parsed.hostname:raise ValueError()
        except ValueError:raise PolicyError('只能临时放行普通网页') from None
        channels=data.get('channels',[])
        if not isinstance(channels,list) or len(channels)>64 or any(not isinstance(c,str) or len(c)>2048 for c in channels):
            raise PolicyError('频道信息无效')
        answer=data.get('answer')
        if answer is not None and (not isinstance(answer,str) or len(answer)>5000):raise PolicyError('验证内容无效')
        engine=self.engine
        with engine.store.lock:
            block=engine.find(data.get('id'))
            decision=engine.evaluate(url,channels,active=True)
            if block['id'] not in {b['id'] for b in decision['blocks']}:raise PolicyError('此网页目前未被该规则拦截')
            lock=block['lock']
            method=lock['type'] if engine.locked(block) else 'none'
            if method not in {'none','text','password'}:raise PolicyError('此规则的锁定条件不允许临时放行')
            if method=='text':
                if answer is None:return {'id':block['id'],'method':'text','challenge':lock['text']}
                if answer!=lock['text']:raise PolicyError('文本不一致，请完整输入')
            if method=='password':
                if engine.now()<lock.get('retry_at',0):raise PolicyError('请稍后重试密码')
                if answer is None:return {'id':block['id'],'method':'password'}
                if not password_ok(answer,lock['hash']):
                    lock['retry_at']=engine.now()+2
                    engine.store.save()
                    raise PolicyError('密码不正确')
            self._valid()
            key=(context,tab,block['id'])
            if key not in self.grants and len(self.grants)>=512:raise PolicyError('临时放行数量已达上限，请先关闭部分标签页')
            grant={'revision':self.revision(block),'until':engine.monotonic()+minutes*60}
            self.grants[key]=grant
            return {'id':block['id'],'tab':tab,'remaining':minutes*60,'revision':grant['revision'],'granted':True}
