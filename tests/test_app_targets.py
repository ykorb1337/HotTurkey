import json
import plistlib
import tempfile
import unittest
from pathlib import Path

from hotturkey.app_targets import ApplicationTargets, app_info, key_values, steam_shortcut_id
from hotturkey.engine import Engine
from hotturkey.store import Store


class ApplicationTargetTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.root=Path(self.temp.name)
        self.steam=self.root/'Steam'
        self.now=100
        self.targets=ApplicationTargets(steam_root=self.steam,app_roots=[self.root/'Applications'],clock=lambda:self.now)
    def tearDown(self):self.temp.cleanup()

    def shortcut(self,appid='1234'):
        app=self.root/'Applications/Shortcut.app'
        binary=app/'Contents/MacOS/run.sh';binary.parent.mkdir(parents=True,exist_ok=True)
        binary.write_text('#!/bin/bash\n# autogenerated file\nopen steam://run/'+appid+'\n')
        (app/'Contents/Info.plist').write_bytes(plistlib.dumps({'CFBundleExecutable':'run.sh'})+b'\0\0')
        return app

    def manifest(self,library=None,directory='Game Name',appid='1234'):
        library=library or self.steam
        file=library/'steamapps'/f'appmanifest_{appid}.acf';file.parent.mkdir(parents=True,exist_ok=True)
        file.write_text('"AppState" { "appid" "'+appid+'" "installdir" "'+directory+'" }')
        return library/'steamapps/common'/directory

    def test_xml_plist_with_steam_trailing_nuls(self):
        app=self.shortcut()
        self.assertEqual(app_info(app)['CFBundleExecutable'],'run.sh')
        self.assertEqual(steam_shortcut_id(app),'1234')

    def test_binary_plist_is_not_trimmed(self):
        app=self.shortcut()
        (app/'Contents/Info.plist').write_bytes(plistlib.dumps({'CFBundleIdentifier':'local.fixture'},fmt=plistlib.FMT_BINARY))
        self.assertEqual(app_info(app)['CFBundleIdentifier'],'local.fixture')

    def test_shortcut_resolves_real_game_not_similarly_named_neighbor(self):
        app=self.shortcut();game=self.manifest()
        with StoreContext(self.root/'state') as store:
            engine=Engine(store);engine.application_targets=self.targets
            block=engine.save_block({'name':'Fixture','applications':[str(app)]})
            self.assertTrue(engine.app_matches(block,{'path':str(game/'Actual.app'),'executable':str(game/'Actual.app/Contents/MacOS/Actual')}))
            self.assertFalse(engine.app_matches(block,{'path':str(game)+' Other/Actual.app'}))

    def test_external_library_and_escaped_path(self):
        external=self.root/'External "Disk"'
        folder=self.steam/'steamapps/libraryfolders.vdf';folder.parent.mkdir(parents=True)
        folder.write_text('"libraryfolders" { "1" { "path" '+json.dumps(str(external))+' } }')
        game=self.manifest(external)
        self.assertIn('folder:'+str(game),self.targets(str(self.shortcut())))

    def test_legacy_flat_library_list(self):
        external=self.root/'External'
        folder=self.steam/'steamapps/libraryfolders.vdf';folder.parent.mkdir(parents=True)
        folder.write_text('"LibraryFolders" { "1" '+json.dumps(str(external))+' }')
        self.assertIn('folder:'+str(self.manifest(external)),self.targets('steam:1234'))

    def test_install_after_shortcut_created_is_discovered(self):
        app=self.shortcut()
        self.assertEqual(self.targets(str(app)),(str(app),))
        game=self.manifest();self.now+=5
        self.assertIn('folder:'+str(game),self.targets(str(app)))

    def test_traversal_install_directory_rejected(self):
        self.manifest(directory='../Other')
        self.assertEqual(self.targets('steam:1234'),('steam:1234',))

    def test_manifest_for_wrong_app_rejected(self):
        file=self.steam/'steamapps/appmanifest_1234.acf';file.parent.mkdir(parents=True)
        file.write_text('"AppState" { "appid" "999" "installdir" "Other" }')
        self.assertEqual(self.targets('steam:1234'),('steam:1234',))

    def test_no_arbitrary_script_execution_or_url_substring_matching(self):
        app=self.shortcut()
        binary=app/'Contents/MacOS/run.sh'
        binary.write_text('echo "open steam://run/1234"\ntouch '+str(self.root/'must-not-exist'))
        self.assertIsNone(steam_shortcut_id(app))
        self.assertFalse((self.root/'must-not-exist').exists())

    def test_bundle_rule_has_path_fallback(self):
        app=self.shortcut()
        (app/'Contents/Info.plist').write_bytes(plistlib.dumps({'CFBundleIdentifier':'local.fixture'}))
        self.assertIn('folder:'+str(app),self.targets('bundle:local.fixture'))

    def test_steam_client_bundle_without_app_extension(self):
        app=self.steam/'Steam.AppBundle/Steam'
        info=app/'Contents/Info.plist';info.parent.mkdir(parents=True)
        info.write_bytes(plistlib.dumps({'CFBundleIdentifier':'com.valvesoftware.steam'}))
        self.assertIn('folder:'+str(app),self.targets('bundle:com.valvesoftware.steam'))

    def test_keyvalues_comments_and_malformed_data(self):
        self.assertEqual(key_values(b'// comment\n"root" { "key" "value" }'),{'root':{'key':'value'}})
        for value in [b'"root" {',b'"root" "value" }',b'unquoted "x"',b'"root" { "key" }']:
            with self.subTest(value=value),self.assertRaises(ValueError):key_values(value)


class StoreContext:
    def __init__(self,path):self.path=path
    def __enter__(self):self.store=Store(self.path);return self.store
    def __exit__(self,*args):self.store.db.close()
